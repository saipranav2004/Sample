// Downloads the site's fonts from Google Fonts once, so production serves them
// itself (no third-party request, no visitor IP sent to Google).
// Run: node scripts/fetch-fonts.mjs   (output is committed in fonts/)
import { writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const FAMILIES = [
  'family=Hanken+Grotesk:wght@300;400;500;600;700&family=JetBrains+Mono:wght@400;500;600&family=Sora:wght@600'
];
const KEEP = new Set(['latin', 'latin-ext']);
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/140.0 Safari/537.36';

await mkdir('fonts', { recursive: true });
let css = '/* Self-hosted fonts. Generated by scripts/fetch-fonts.mjs. Licences in fonts/LICENSES.md (SIL Open Font License 1.1). */\n';
const seen = new Map();
for (const q of FAMILIES) {
  const src = await (await fetch(`https://fonts.googleapis.com/css2?${q}&display=swap`, { headers: { 'user-agent': UA } })).text();
  const blocks = src.split(/(?=\/\* [a-z-]+ \*\/)/);
  for (const b of blocks) {
    const subset = (b.match(/^\/\* ([a-z-]+) \*\//) || [])[1];
    if (!subset || !KEEP.has(subset)) continue;
    let out = b;
    for (const [, url] of b.matchAll(/url\((https:[^)]+\.woff2)\)/g)) {
      if (!seen.has(url)) {
        const buf = Buffer.from(await (await fetch(url)).arrayBuffer());
        const fam = (b.match(/font-family: '([^']+)'/) || [])[1].toLowerCase().replace(/\s+/g, '-');
        const name = `${fam}-${subset}-${createHash('sha256').update(buf).digest('hex').slice(0, 8)}.woff2`;
        await writeFile(`fonts/${name}`, buf);
        seen.set(url, name);
      }
      out = out.replace(url, seen.get(url));
    }
    css += out;
  }
}
await writeFile('fonts/fonts.css', css);
console.log(`fonts: ${seen.size} files`);
